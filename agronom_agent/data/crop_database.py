def get_crop(name: str) -> CropRequirements | None:
    """Obté el perfil d'un cultiu pel nom."""
    key = name.lower().strip()
    if key in CROP_DATABASE:
        return CROP_DATABASE[key]
    # Cerca parcial
    for k, v in CROP_DATABASE.items():
        if key in k or key in v.crop_name.lower():
            return v
    return None


def list_crops() -> list[str]:
    """Retorna la llista de cultius disponibles."""
    return sorted(CROP_DATABASE.keys())
